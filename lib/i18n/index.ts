/**
 * Convert numbers to Bengali digits
 */
export function toBanglaNumeral(num: number | string): string {
  const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (d) => bnDigits[Number(d)]);
}

/**
 * Format Bangladesh Taka (BDT / ৳) with South Asian Lakh / Crore system
 */
export function formatBDT(amount: number | string, locale: Locale = 'bn'): string {
  const n = typeof amount === 'string' ? parseFloat(amount) : amount;
  if (isNaN(n)) return locale === 'bn' ? '৳০' : '৳0';

  if (locale === 'bn') {
    if (Math.abs(n) >= 10000000) {
      const cr = (n / 10000000).toFixed(2);
      return `৳${toBanglaNumeral(cr)} কোটি`;
    }
    if (Math.abs(n) >= 100000) {
      const lk = (n / 100000).toFixed(2);
      return `৳${toBanglaNumeral(lk)} লাখ`;
    }
    return `৳${toBanglaNumeral(n.toLocaleString('en-IN'))}`;
  }

  // English formatting
  if (Math.abs(n) >= 10000000) {
    return `৳${(n / 10000000).toFixed(2)} Cr`;
  }
  if (Math.abs(n) >= 100000) {
    return `৳${(n / 100000).toFixed(2)} L`;
  }
  return `৳${n.toLocaleString('en-IN')}`;
}

/**
 * Localizes plan/subscription refusals returned by the API (limit reached,
 * subscription inactive, feature not enabled, suspended). Falls back to the
 * server's own message for any other error. {limit} is read from the message.
 */
export function localizeApiError(lang: Locale, code: string | undefined, fallback?: string): string {
  const table = DICTIONARY[lang].subscription.errors as Record<string, string>;
  const template = code ? table[code] : undefined;
  if (!template) return fallback || code || '';
  const m = fallback?.match(/up to (\d+)/);
  const limit = m ? (lang === 'bn' ? toBanglaNumeral(m[1]) : m[1]) : '';
  return template.replace('{limit}', limit);
}

/**
 * Exact BDT amount (no lakh/crore abbreviation) for fee tables and totals where
 * a rounded "৳1.00 L" would misstate the money. Whole taka drop the decimals.
 */
export function formatBDTExact(amount: number | string, locale: Locale = 'bn'): string {
  const n = typeof amount === 'string' ? parseFloat(amount) : amount;
  if (isNaN(n)) return locale === 'bn' ? '৳০' : '৳0';
  const body = n.toLocaleString('en-IN', { minimumFractionDigits: 0, maximumFractionDigits: 2 });
  return `৳${locale === 'bn' ? toBanglaNumeral(body) : body}`;
}

/**
 * Format date in DD/MM/YYYY in Asia/Dhaka timezone
 */
export function formatDhakaDate(dateInput: Date | string | number): string {
  const d = new Date(dateInput);
  if (isNaN(d.getTime())) return '';

  const formatter = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Asia/Dhaka',
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
  });

  return formatter.format(d);
}

/**
 * Pick the Bangla text when the UI is in Bangla and it exists, otherwise the
 * English text (or whichever one is available).
 */
export function pickLocalized(lang: Locale, en?: string | null, bn?: string | null): string {
  if (lang === 'bn' && bn) return bn;
  return en || bn || '';
}

/** Render a number in the active locale's digits (e.g. 12.5 → ১২.৫ in Bangla). */
export function localizeNumber(lang: Locale, n: number | string | null | undefined): string {
  if (n === null || n === undefined || n === '') return '';
  const str = typeof n === 'number' ? String(Math.round(n * 100) / 100) : n;
  return lang === 'bn' ? toBanglaNumeral(str) : str;
}
